def palindrome(s):
    return s==s[::-1] 
def prime(s):
    if s<2: return False
    if s<4: return True
    if s%2==0 or s%3==0: return False
    i=5
    while i*i<=s:
        if s%i==0 or s%(i+2)==0: return False
        i+=6
    return True
def binary_search(ar,tar):
    lo,hi=0,len(ar)-1
    while lo<=hi:
        mid=(lo+hi)//2
        if ar[mid]==tar:
            return mid
        else:
            if ar[mid]<tar:
                lo=mid+1
            else:
                hi=mid-1
    return -1
def binary_search_dup(ar, tar, first_occurence=True):
    if first_occurence:
        idx = bisect.bisect_left(ar, tar)
        return idx if idx < len(ar) and ar[idx] == tar else -1
    else:
        idx = bisect.bisect_right(ar, tar) - 1
        return idx if idx >= 0 and ar[idx] == tar else -1
def prefix_sum(a,n):
    d=[0]+a
    pref=[0]*(n+1)
    for x in range(1,n+1):
        pref[x]=pref[x-1]+d[x]
    return pref
